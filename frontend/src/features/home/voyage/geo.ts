/* ─────────────────────────── Sampling ─────────────────────────── */

function inside(poly: LonLat[], lon: number, lat: number) {
  let hit = false
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i]
    const [xj, yj] = poly[j]
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit
  }
  return hit
}

export const isLand = (lon: number, lat: number) =>
  lat < -70 || (LAND.some(p => inside(p, lon, lat)) && !WATER.some(p => inside(p, lon, lat)))

