/** Points as unit vectors, for turning without trigonometry per frame. */
export interface Points {
  n: number
  x: Float32Array
  y: Float32Array
  z: Float32Array
}

/** A place as a unit vector: x toward 90° E, y north, z toward 0°, 0°. */
export const unit = (lon: number, lat: number): [number, number, number] => {
  const la = (lat * Math.PI) / 180
  const lo = (lon * Math.PI) / 180
  return [Math.cos(la) * Math.sin(lo), Math.sin(la), Math.cos(la) * Math.cos(lo)]
}

/**
 * A coastline as unit vectors, with no edge longer than `step` degrees, so
 * it stays a curve when it is drawn on the sphere at any size.
 */
function densify(ring: LonLat[], step: number): Float32Array {
  const out: number[] = []
  for (let i = 0; i < ring.length; i++) {
    const [lon0, lat0] = ring[i]
    const [lon1, lat1] = ring[(i + 1) % ring.length]
    // The short way round: 180° and −180° are the same meridian.
    const dlon = ((lon1 - lon0 + 540) % 360) - 180
    const n = Math.max(1, Math.ceil(Math.hypot(dlon, lat1 - lat0) / step))
    for (let k = 0; k < n; k++) out.push(...unit(lon0 + (dlon * k) / n, lat0 + ((lat1 - lat0) * k) / n))
  }
  return new Float32Array(out)
}

export interface World {
  /** The land, each ring flat [x, y, z, x, y, z, …]. */
  land: Float32Array[]
  /** The inland seas, cut back out of it. */
  seas: Float32Array[]
  /** Cities: lit on the night side. */
  lights: Points
}

let world: World | null = null

/** The world, built once: coastlines for filling, and the lights of its cities. */
export function theWorld(): World {
  if (!world) {
    // Seeded: the same cities for every visitor.
    const rand = random(29)
    const xs: number[] = [], ys: number[] = [], zs: number[] = []
    for (const [lon0, lat0, lon1, lat1] of LIT) {
      const n = Math.round(((lon1 - lon0) * (lat1 - lat0)) / 9)
      for (let k = 0; k < n; k++) {
        const lon = lon0 + rand() * (lon1 - lon0)
        const lat = lat0 + rand() * (lat1 - lat0)
        if (!isLand(lon, lat)) continue
        const [x, y, z] = unit(lon, lat)
        xs.push(x); ys.push(y); zs.push(z)
      }
    }
    world = {
      land: LAND.map(ring => densify(ring, 1.5)),
      seas: WATER.map(ring => densify(ring, 1.5)),
      lights: { n: xs.length, x: new Float32Array(xs), y: new Float32Array(ys), z: new Float32Array(zs) },
    }
  }
  return world
}
